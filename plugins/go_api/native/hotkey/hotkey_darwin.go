package hotkey

/*
#cgo LDFLAGS: -framework AppKit -framework Carbon -framework CoreFoundation -framework CoreGraphics
#include <stdint.h>
int32_t flclash_register_hotkey(uint32_t key, uint32_t modifiers, uint32_t id, uint32_t media, uintptr_t *ref);
void flclash_unregister_hotkey(uint32_t key, uint32_t modifiers, uint32_t media, uintptr_t ref);
*/
import "C"

import (
	"fmt"
	"sync/atomic"
)

type macBackend struct{}

var callback atomic.Pointer[func(uint32)]

func newBackend(pressed func(uint32)) (backend, error) {
	callback.Store(&pressed)
	return macBackend{}, nil
}

//export flclashHotkeyPressed
func flclashHotkeyPressed(id C.uint32_t) {
	if pressed := callback.Load(); pressed != nil {
		(*pressed)(uint32(id))
	}
}

func (macBackend) register(usage uint32, modifiers modifiers, id uint32) (func(), error) {
	key, ok := macKeys[usage]
	media := C.uint32_t(0)
	if !ok {
		key, ok = macMediaKeys[usage]
		if !ok {
			return nil, unsupportedKey(usage)
		}
		media = 1
	}
	var ref C.uintptr_t
	status := C.flclash_register_hotkey(C.uint32_t(key), C.uint32_t(modifiers), C.uint32_t(id), media, &ref)
	if status != 0 {
		return nil, fmt.Errorf("unable to register macOS hotkey (OSStatus %d)", status)
	}
	return func() {
		C.flclash_unregister_hotkey(C.uint32_t(key), C.uint32_t(modifiers), media, ref)
	}, nil
}

